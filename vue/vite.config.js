/*
 * ================================================================
 *  Vite 配置文件
 *  作用：Vite 项目的核心配置中心
 * ================================================================
 *  1. 环境管理   - 根据 development/production 加载不同配置
 *  2. 插件管理   - 集成 Vue 插件、SVG 图标插件等
 *  3. 路径管理   - 配置 @ 和 ~ 别名，简化导入路径
 *  4. 开发服务器 - 端口、主机、热更新、代理（解决跨域）
 * ================================================================
 */

// 从 vite 导入核心工具函数
// defineConfig: 提供类型提示，让配置更安全
// loadEnv: 加载 .env 文件中的环境变量
import { defineConfig, loadEnv } from 'vite'

// Node.js path 模块，用于拼接文件路径（处理跨平台兼容）
import path from 'path'

// 导入自定义的插件工厂函数（管理 Vue、SVG 等插件）
import createVitePlugins from './vite/plugins'

// ================================================================
// 导出 Vite 配置（函数式配置，可以根据命令动态调整）
// ================================================================
export default defineConfig(({ mode, command }) => {
  // ---------- 1. 加载环境变量 ----------
  // mode: 当前模式，如 development / production
  // process.cwd(): 获取项目根目录路径
  const env = loadEnv(mode, process.cwd())

  // ---------- 2. 返回配置对象 ----------
  return {
    // ============================================================
    //  一、基础配置
    // ============================================================
    // 部署时的基础路径
    // - 开发环境：使用 '/'
    // - 生产环境：如果部署在子路径下，如 https://example.com/admin/，则改成 '/admin/'
    base: '/',

    // ============================================================
    //  二、插件配置
    // ============================================================
    // 调用插件工厂函数，生成插件数组
    // env: 环境变量对象，插件可能需要使用
    // command === 'build': 判断当前是否为构建命令，有些插件在开发/构建时行为不同
    plugins: createVitePlugins(env, command === 'build'),

    // ============================================================
    //  三、路径解析配置
    // ============================================================
    resolve: {
      // 路径别名（导入时用别名代替长路径，提高可读性和可维护性）
      alias: {
        // '~' 指向项目根目录（通常用于配置或静态资源）
        '~': path.resolve(__dirname, './'),
        // '@' 指向 src 目录（最常用，所有业务代码都在这里）
        '@': path.resolve(__dirname, './src'),
        // 示例：'@components': path.resolve(__dirname, './src/components')
      },
      // 自动解析的扩展名
      // 导入时可以省略这些扩展名：import App from '@/App' → 实际找 @/App.vue
      extensions: [
        '.mjs',    // ES 模块
        '.js',     // JavaScript
        '.ts',     // TypeScript
        '.jsx',    // React JSX
        '.tsx',    // TypeScript + JSX
        '.json',   // JSON 数据
        '.vue'     // Vue 单文件组件（最常用）
      ]
    },

    // ============================================================
    //  四、开发服务器配置（仅开发环境生效，打包后无效）
    // ============================================================
    server: {
      // ---------- 1. 服务器基础设置 ----------
      port: 90,               // 端口号（如果被占用，Vite 会自动尝试下一个）
      host: true,             // true：监听所有网络接口（允许局域网访问，如手机调试）
                              // 也可以指定 IP：'0.0.0.0' 或 '192.168.1.100'
      open: true,             // 启动后自动在浏览器中打开页面

      // ---------- 2. 代理配置（解决跨域问题） ----------
      // 原理：开发时前端跑在 localhost:90，后端跑在 localhost:8080
      // 浏览器同源策略会阻止跨域请求，但代理可以把特定请求转发给后端
      // 让浏览器感觉所有请求都是发给同一个源（localhost:90）
      proxy: {
        // ============================================================
        // 代理规则一：转发 API 请求（/base → 后端 /）
        // ============================================================
        // 所有以 /base 开头的请求，都会被转发到后端服务器
        // 示例：前端请求 /base/login → 代理转发 → 后端 /login
        '/base': {
          target: 'http://localhost:8080', // 转发目标（后端地址）
          changeOrigin: true,               // 修改请求头中的 Host 为目标地址，避免后端校验失败

          // URL 重写：去掉 /base 前缀
          // 为什么？后端接口路径是 /login，不是 /base/login
          // 如果不重写，后端会收到 /base/login，找不到对应接口，返回 404
          rewrite: (path) => path.replace(/^\/base/, '')
        },

        // ============================================================
        // 代理规则二：转发静态资源请求（/profile → 后端 /profile）
        // ============================================================
        // 所有以 /profile 开头的请求，直接转发到后端
        // 示例：前端请求 /profile/avatar/xxx.jpg → 代理转发 → 后端 /profile/avatar/xxx.jpg
        // 为什么需要？
        // 1. 用户上传的头像存储在服务器磁盘上（如 ./file/avatar/xxx.jpg）
        // 2. 后端通过 ResourcesConfig 将 /profile/** 映射到磁盘目录
        // 3. 前端需要能访问这些文件，但前端开发服务器不认识 /profile 路径
        // 4. 通过代理，把 /profile 请求交给后端处理
        // 5. 后端返回文件内容，前端就能显示头像了
        '/profile': {
          target: 'http://localhost:8080',
          changeOrigin: true
          // 注意：这里没有 rewrite
          // 因为后端 ResourcesConfig 配置的路径就是 /profile/**
          // 所以不需要改变路径，直接转发即可
        }
      }
    }

    // ============================================================
    //  五、构建配置（生产环境优化，可在此扩展）
    // ============================================================
    // build: {
    //   // 构建时输出的目录名
    //   outDir: 'dist',
    //   // 生成 source map（方便调试）
    //   sourcemap: false,
    //   // 代码分包策略（优化加载速度）
    //   rollupOptions: { ... }
    // }
  }
})